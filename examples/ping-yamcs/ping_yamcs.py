#!/usr/bin/env python3
"""The ping example with Yamcs as the ground station.

The vehicle is the ping example's -- a ``ping`` node that answers each ping
with its time on the end -- and so is what is timed: the round trip, and the
two halves of it, up and down. What differs is the ground end of the link:
Yamcs (https://yamcs.org), which speaks CCSDS packets, so the configuration's
gateway is ``yamcs``. Every packet to and from the ground then carries a CCSDS
primary header, which tcspecial adds as each goes and takes off as each
arrives: the beacon, CONNECT and its answer, the ping and its answer.

This program puts the two together:

* it writes a Yamcs configuration from the tcspecial one -- the ports, and the
  APIDs Yamcs tells the packets apart by -- into a run directory, with a
  mission database of tcspecial's own XTCE (``tcslibgs/xtce``) and a wrapper
  that puts the header around it, generated by ``tcslibgs/yamcs.py`` with a
  container or a command for every APID the configuration counts: the ping
  and its answer as the ping node's interface document,
  ``tcslibgs/xtce/ping.xtce``, lays them out, field by field, as text;
* it starts Yamcs on it, and tcspecial on the configuration, each killed when
  this program exits, however it exits;
* it has Yamcs send a CONNECT carrying the configuration's checksum until the
  vehicle answers with it -- the vehicle sends nothing down, ping answers
  included, until it has -- and then sends pings through Yamcs and reads the
  answers back from it, over Yamcs's REST API;
* it shows them in the ping example's window, the beacon panel and the ping
  panel, or with ``--pings`` prints them with no window.

What it shares with other ground stations it shares rather than copies: the
Yamcs run, its REST API, CONNECT and the beacon through Yamcs are
``python/tcslib/yamcs_ground.py``'s, which thermostat-yamcs uses too; the
ping link's bookkeeping and the window are ``examples/ping-common``'s,
which the ping example uses too.

Yamcs's web interface, at http://localhost:16090 by default, shows every
packet and parameter meanwhile: the beacon, the answers, and the pings, a
ping's command and its answer's parameters as the text they are.

Usage, from the repository's root, with Yamcs unpacked somewhere::

    python3 examples/ping-yamcs/ping_yamcs.py --yamcs ~/yamcs-5.14.0
    python3 examples/ping-yamcs/ping_yamcs.py --pings 3   # no window
    python3 examples/ping-yamcs/ping_yamcs.py --describe  # what it read

``--yamcs`` is the directory a Yamcs release unpacks to, holding
``bin/yamcsd``; ``$YAMCS_HOME`` says it when ``--yamcs`` does not. With
neither ``--pings`` nor ``--describe`` it opens the window, and pings each
time ``Send ping`` is pressed. ``--no-vehicle`` leaves tcspecial to somebody
else, and ``--no-yamcs`` uses a Yamcs already running on the run directory's
configuration.
"""

import argparse
import os
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "python"))
# What this example shares with the ping example: the ping link's
# bookkeeping and the window.
sys.path.insert(0, str(HERE.parent / "ping-common"))

from tcslib.beacon import Schedule  # noqa: E402
from tcslib.processes import Vehicle  # noqa: E402
from tcslib.yamcs_ground import (  # noqa: E402
    Yamcs, YamcsBeacons, command_settings, connect, first_beacon,
    write_yamcs, yamcs_home)
from tcslibgs import configuration, ping, ping_packet  # noqa: E402
from tcslibgs import yamcs as generated  # noqa: E402
from ping_ground import Exchange, Pinger, report  # noqa: E402
from ping_window import run_the_window, the_one  # noqa: E402

#: Where Yamcs's web interface and REST API are, unless --http-port says.
HTTP_PORT = 16090

#: The Yamcs instance this example runs.
INSTANCE = "ping"

#: The ping command's arguments, as ``tcslibgs/xtce/ping.xtce`` names them,
#: by the field of :class:`tcslibgs.ping_packet.Ping` that each is: what a
#: ping is split into by the code generated from that document, so that it
#: is split as the document says.
PING_ARGUMENTS = {"count": "Count", "sent_seconds": "SentSeconds",
                  "sent_nanoseconds": "SentNanoseconds"}

#: The answer's parameters, as the document names them, by the field of
#: :class:`tcslibgs.ping_packet.PingReply` that each is: what an answer is
#: put back together from. Its prefix and its space are constants, which
#: the generated code writes itself.
REPLY_PARAMETERS = {
    "reply_count": "ReplyCount",
    "reply_sent_seconds": "ReplySentSeconds",
    "reply_sent_nanoseconds": "ReplySentNanoseconds",
    "reply_answered_seconds": "ReplyAnsweredSeconds",
    "reply_answered_nanoseconds": "ReplyAnsweredNanoseconds"}


def arguments(argv):
    """Reads the command line.

    Args:
        argv: The arguments, without the program's name.

    Returns:
        The options, as :mod:`argparse` gives them.
    """
    parser = argparse.ArgumentParser(description="Ping a tcspecial vehicle "
                                                 "through Yamcs.")
    parser.add_argument(
        "configuration", nargs="?", default=str(HERE / "ping-yamcs.xtcs"),
        help="the tcspecial configuration (default: ping-yamcs.xtcs)")
    parser.add_argument("--yamcs", default=os.environ.get("YAMCS_HOME"),
                        help="where Yamcs is unpacked (default: $YAMCS_HOME)")
    parser.add_argument("--run-dir", default="/tmp/ping-yamcs",
                        help="where Yamcs's configuration and data are written "
                             "(default: /tmp/ping-yamcs)")
    parser.add_argument("--http-port", type=int, default=HTTP_PORT,
                        help=f"Yamcs's web port (default: {HTTP_PORT})")
    parser.add_argument("--pings", type=int, metavar="N",
                        help="send N pings, print each exchange, and stop, "
                             "with no window")
    parser.add_argument("--describe", action="store_true",
                        help="print what was read and the Yamcs settings, and "
                             "stop")
    parser.add_argument("--no-vehicle", action="store_true",
                        help="do not start tcspecial")
    parser.add_argument("--no-yamcs", action="store_true",
                        help="do not start Yamcs; use one already running")
    parser.add_argument("--tcspecial", help="the tcspecial program to run")
    parser.add_argument("--tcsverify",
                        help="the tcsverify program that gives the "
                             "configuration's checksum")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="say what it is doing")
    return parser.parse_args(argv)


#: Whether to print status messages: ``-v`` or ``--verbose``.
VERBOSE = False


def status(text):
    """Say ``text`` on stderr, if asked to with ``-v``."""
    if VERBOSE:
        print(text, file=sys.stderr, flush=True)


class Setup:
    """What the program read out of the configuration, and the Yamcs
    settings that follow from it.

    Args:
        options: The command line's options, from :func:`arguments`.

    Raises:
        ValueError: The configuration is wrong for this program.
        OSError: The configuration cannot be read.
    """

    def __init__(self, options):
        self.path = Path(options.configuration).resolve()
        self.config = configuration.load(self.path)
        said = self.config.tcspecial
        if said.get("gateway") != "yamcs":
            raise ValueError(f"{self.path}: its gateway is "
                             f"{said.get('gateway')!r}, and this program is "
                             "Yamcs's: say gateway: yamcs")
        self.gateway = the_one(self.config.nodes, "gateway_yamcs", None)
        self.node = the_one(self.config.nodes, "ping", None)
        self.uplink = self.config.uplink(self.gateway)
        self.downlink = self.config.downlink(self.gateway, self.node)
        self.beacon = self.config.beacon_link()
        self.beacon_interval = self.config.beacon_interval()
        self.command = self.config.command_link().recv
        self.beacon_apid = self.config.beacon_apid()
        self.cmd_apid = self.config.command_apid()
        self.uplink_apid = self.config.uplink_apid(self.gateway)
        self.reply_apid = self.config.downlink_apid(self.gateway, self.node)
        # The command a ping goes as, which the ping node's document names,
        # where every node the gateway node's data goes to is a ping node;
        # anywhere else the data goes whole, as no document lays it out.
        uplink = next(uplink for uplink in generated.uplinks(self.config)
                      if uplink.name == self.gateway)
        if uplink.document is None:
            raise ValueError(f'{self.path}: "{self.gateway}" sends its data '
                             "to nodes that are not all ping nodes, so Yamcs "
                             "has no ping command for it: draw its "
                             "moc-out links to the ping node alone")
        self.ping_command = generated.qualified(uplink.command)
        # And the parameters its answer arrives as.
        self.ping_reply = [generated.qualified(name)
                           for name in REPLY_PARAMETERS.values()]
        self.digest, self.why_no_digest = configuration.digest(
            self.path, options.tcsverify)

    def yamcs_settings(self, run_dir, http_port):
        """The names the Yamcs templates are filled in with, and the facts
        the configuration states that --describe prints.

        Args:
            run_dir:   Where Yamcs's configuration and data go.
            http_port: Yamcs's web port.

        Returns:
            A dictionary of each template name and its value.
        """
        # What the configuration says, which tcslibgs/yamcs.py writes into
        # Yamcs's links and its mission database, and which --describe
        # prints for the tests to hold to the Rust. Yamcs reaches
        # tcspecial's command link where the vehicle takes commands; a
        # vehicle that takes them on every interface is reached here.
        said = command_settings(self.config)
        return {
            "http_port": str(http_port),
            "data_dir": str(run_dir / "data"),
            "run_dir": str(run_dir),
            "cmd_host": said["cmd_host"],
            "cmd_port": said["cmd_port"],
            "uplink_host": generated.local(self.uplink.address),
            "uplink_port": str(self.uplink.port),
            "downlink_port": str(self.downlink.port),
            "beacon_port": said["beacon_port"],
            "beacon_apid": said["beacon_apid"],
            "cmd_apid": said["cmd_apid"],
            "uplink_apid": str(self.uplink_apid),
            "reply_apid": str(self.reply_apid)}

    def describe(self, run_dir, http_port):
        """The facts, one per line.

        Args:
            run_dir:   Where Yamcs's configuration and data go.
            http_port: Yamcs's web port.

        Returns:
            Each Yamcs setting as ``name value``, then the digest.
        """
        settings = self.yamcs_settings(run_dir, http_port)
        lines = [f"{name} {value}" for name, value in settings.items()]
        return "\n".join(lines + [f"digest {self.digest}"])


class YamcsPinger(Pinger):
    """The ping link through Yamcs: each ping is the command the ping node's
    interface document states, its text split into the document's fields,
    and each answer the document's parameters, its text put back together
    from them.

    The ping example's :class:`ping_ground.Pinger`, keeping what it keeps
    and timing what it times; only how a ping goes and an answer arrives
    differ. The time an answer arrived is when Yamcs received it, to the
    millisecond, which is as finely as Yamcs says.

    Args:
        yamcs:   The Yamcs to send through.
        command: The qualified name of the command a ping goes as.
        reply:   The qualified names of the parameters an answer arrives
                 as, in the order of :data:`REPLY_PARAMETERS`.
        clock:   What gives the time now, in nanoseconds since the epoch.
    """

    def __init__(self, yamcs, command, reply, clock=time.time_ns):
        self._yamcs = yamcs
        self._command = command
        self._reply = reply
        self._clock = clock
        self._count = 0
        self._exchange = Exchange()
        latest = yamcs.parameters(reply)
        self._seen = latest[1] if latest else 0

    def ping(self):
        """Send the next ping through Yamcs, and say what it was.

        Returns:
            The ping sent, as text.
        """
        self._count += 1
        at = self._clock()
        message = ping.message(self._count, at)
        fields = ping_packet.Ping.decode(message.encode("ascii"))
        self._yamcs.issue(self._command,
                          {argument: getattr(fields, field)
                           for field, argument in PING_ARGUMENTS.items()})
        self._exchange = Exchange(sent=message, sent_at=at,
                                  received=self._exchange.received)
        return message

    def receive(self, timeout):
        """Wait for Yamcs to receive an answer it had not before.

        Args:
            timeout: How long to wait, in seconds.

        Returns:
            Whether one arrived.
        """
        deadline = time.monotonic() + timeout
        while True:
            latest = self._yamcs.parameters(self._reply)
            if latest is not None and latest[1] > self._seen:
                values, self._seen = latest
                self.answered(answer_of(values, self._reply), self._seen)
                return True
            if time.monotonic() >= deadline:
                return False
            time.sleep(0.02)

    def close(self):
        """Nothing to close: Yamcs holds the sockets."""


def answer_of(values, names):
    """An answer to a ping, put back together from its fields as Yamcs read
    them, by the code generated from the ping node's interface document.

    Args:
        values: Each field's value, by its parameter's qualified name.
        names:  The parameters' qualified names, in the order of
                :data:`REPLY_PARAMETERS`.

    Returns:
        The answer's bytes; for fields that do not fit the document,
        what they say, which is then not an answer, and shown as such.
    """
    fields = {field: values[name]
              for field, name in zip(REPLY_PARAMETERS, names)}
    try:
        return ping_packet.PingReply(**fields).to_bytes()
    except (ping_packet.pk.PacketError, TypeError) as why:
        return f"{fields}: {why}".encode()


def ping_and_print(pinger, count):
    """Send ``count`` pings, one after another, and print each exchange.

    Args:
        pinger: The ping link.
        count:  How many.

    Returns:
        The exit status: nought if every ping was answered, one if not.
    """
    answered_all = True
    for _ in range(count):
        print(f"sent: {pinger.ping()}", flush=True)
        deadline = time.monotonic() + 2
        while time.monotonic() < deadline:
            if (pinger.receive(max(deadline - time.monotonic(), 0.01))
                    and pinger.exchange().received_at):
                break
        lines, answered = report(pinger.exchange())
        for line in lines:
            print(line, flush=True)
        answered_all = answered_all and answered
    return 0 if answered_all else 1


def main(argv):
    """Runs the example.

    Args:
        argv: The command line, without the program's name.

    Returns:
        The exit status.
    """
    global VERBOSE
    options = arguments(argv)
    VERBOSE = options.verbose
    run_dir = Path(options.run_dir).resolve()
    try:
        setup = Setup(options)
    except (ValueError, OSError) as why:
        print(f"ping_yamcs: {why}", file=sys.stderr)
        return 2
    if options.describe:
        print(setup.describe(run_dir, options.http_port))
        return 0
    if setup.digest is None:
        print(f"ping_yamcs: no checksum for CONNECT: {setup.why_no_digest}",
              file=sys.stderr)
        return 2
    yamcs = Yamcs(options.yamcs, run_dir, options.http_port, INSTANCE)
    vehicle = None
    try:
        if not options.no_yamcs:
            try:
                home = yamcs_home(options.yamcs)
            except ValueError as why:
                print(f"ping_yamcs: {why}", file=sys.stderr)
                return 2
            write_yamcs(setup.config, run_dir, options.http_port, home,
                        INSTANCE, "ping_yamcs.py")
            status(f"starting Yamcs on {run_dir}")
            yamcs.start()
            status(f"Yamcs is at http://localhost:{options.http_port}")
        if not options.no_vehicle:
            vehicle = Vehicle.for_configuration(setup.path, options.tcspecial,
                                                options.verbose)
            vehicle.start()
        if not connect(yamcs, setup.digest, say=status):
            print("ping_yamcs: the vehicle never answered CONNECT with this "
                  "configuration's checksum", file=sys.stderr)
            return 1
        print("connected: the vehicle is running this configuration",
              flush=True)
        beacons = YamcsBeacons(yamcs, setup.beacon,
                               Schedule.for_interval(setup.beacon_interval),
                               setup.digest, setup.beacon_interval)
        pinger = YamcsPinger(yamcs, setup.ping_command, setup.ping_reply)
        if options.pings is None:
            return run_the_window(setup, beacons, pinger,
                                  title="tcspecial ping through Yamcs",
                                  say=status)
        first_beacon(beacons)
        return ping_and_print(pinger, options.pings)
    except (RuntimeError, ValueError, OSError) as why:
        print(f"ping_yamcs: {why}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 0
    finally:
        if vehicle is not None:
            vehicle.stop()
        if not options.no_yamcs:
            yamcs.stop()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
