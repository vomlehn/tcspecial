//! The generated Rust compiles, and builds the configuration it came from.
//!
//! `tcsgui::codegen` writes a configuration out as Rust, to be compiled into
//! tcspecial along with the node types the configuration uses. A generator
//! whose output is only compared against expected text is a generator that can
//! emit something that does not compile, and nobody would find out until a
//! build of the flight software failed -- so the output is committed here, as
//! `generated/thermostat.rs`, and this test file compiles it.
//!
//! Which makes the compiler the test: the generated code names types from
//! `tcslibgs`, so a change to `Graph`, `Node`, `Link` or `Parameter` that the
//! generator has not kept up with is a build failure here rather than a
//! surprise in somebody's vehicle build. And what it builds is then handed to
//! `Graph::check`, which is the same function the ground tool and the flight
//! software run: a configuration compiled in is held to exactly what a
//! configuration read from a file is held to.
//!
//! The committed file is regenerated by
//! `TCSGUI_WRITE_EXAMPLE=1 cargo test -p tcsgui`, as the shipped examples are.
//! `tcsgui/src/codegen.rs` is where the test that regenerates it lives, next
//! to the generator; this file is only the compiling and the checking.

#[path = "generated/thermostat.rs"]
mod thermostat;

/// What the generator wrote is a configuration that can be flown.
#[test]
fn the_generated_configuration_is_checked_like_any_other() {
    let graph = thermostat::configuration();

    // The same check tcsverify runs on the ground and tcspecial runs again
    // aboard. Nothing to say about it is what a sound configuration gets.
    let problems = graph.check();
    assert!(
        problems.is_empty(),
        "the generated configuration is refused: {:?}",
        problems
            .iter()
            .map(|problem| problem.describe())
            .collect::<Vec<String>>()
    );
}

/// And it is the configuration the shipped example describes.
///
/// Read the file, build the graph from the generated code, and compare what
/// each of them says: the same nodes, the same links, the same groups and the
/// same bindings. A generator that silently dropped a link would otherwise
/// pass the check above, a configuration with one link fewer being a sound
/// configuration.
#[test]
fn the_generated_configuration_is_the_one_the_file_describes() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let read = tcslibgs::graph::Graph::load(root.join("tests/manual/thermostat.yaml"))
        .expect("the shipped example reads");
    let built = thermostat::configuration();

    let named = |graph: &tcslibgs::graph::Graph| {
        let mut names: Vec<String> = graph
            .nodes
            .iter()
            .map(|node| format!("{}:{}", node.name, node.node_type))
            .collect();
        names.sort();
        names
    };
    assert_eq!(named(&read), named(&built), "the nodes differ");

    let linked = |graph: &tcslibgs::graph::Graph| {
        let mut links: Vec<String> = graph
            .links
            .iter()
            .flat_map(|link| {
                link.to
                    .each()
                    .into_iter()
                    .map(|to| format!("{} -> {to}", link.from))
                    .collect::<Vec<String>>()
            })
            .collect();
        links.sort();
        links
    };
    assert_eq!(linked(&read), linked(&built), "the links differ");

    let grouped = |graph: &tcslibgs::graph::Graph| {
        let mut groups: Vec<String> = graph
            .groups
            .iter()
            .map(|group| format!("{}:{}", group.name, group.interval))
            .collect();
        groups.sort();
        groups
    };
    assert_eq!(grouped(&read), grouped(&built), "the groups differ");

    let commanded = |graph: &tcslibgs::graph::Graph| {
        let mut commands: Vec<String> = graph
            .commands
            .iter()
            .map(|command| format!("{} sets {}", command.from, command.sets))
            .collect();
        commands.sort();
        commands
    };
    assert_eq!(commanded(&read), commanded(&built), "the bindings differ");

    // And what tcspecial itself is configured with, which is the section the
    // generator hands to `nest` rather than spelling out.
    assert_eq!(
        read.tcspecial.as_ref().map(tcslibgs::graph::parameters::flatten),
        built.tcspecial.as_ref().map(tcslibgs::graph::parameters::flatten),
        "the tcspecial section differs"
    );
}
