#!/usr/bin/env python3
"""How much memory tcspecial has, watched through Yamcs.

The vehicle is ``memusage.xtcs``'s: a ``gateway_yamcs`` node and three ping
nodes, each running on a thread of its own. Nothing is pinged; what is
shown is memory. This program has Yamcs (https://yamcs.org) send
QUERY_THREADS, on tcspecial's node command link, and reads the answer back
from Yamcs: how much the whole process has mapped, how much is resident and
how much locked, the limit on what it may lock, and, for every thread it
runs, what the thread is for, the stack it was given and the most of that
stack it has used. See "How deep each thread has been" and "Locking memory"
in the tcspecial manual.

More than one tcspecial may be watched at once -- several on one vehicle,
each on a configuration of its own -- in one Yamcs. Each is given an
instance of the one Yamcs server, named after its configuration, because
every tcspecial's answers are laid out by the same mission database, whose
parameters two tcspecials in one instance would share. Yamcs's web
interface, at http://localhost:18090 by default, shows every instance, and
in each a parameter list, ``memusage``, of the answer's parameters.

This program:

* writes a Yamcs server, with an instance for each configuration, into a run
  directory, each instance's links and mission database generated by
  ``tcsprotocol/yamcs.py`` from its configuration;
* starts Yamcs on it, and a tcspecial on each configuration, each killed when
  this program exits, however it exits;
* has Yamcs send each tcspecial a CONNECT carrying its configuration's
  checksum, until it answers with it;
* then, every ``--interval`` seconds, has Yamcs send each one QUERY_THREADS,
  as often as it takes to have every thread, and prints what it answered.

Usage, from the repository's root::

    python3 examples/memusage/memusage.py
    python3 examples/memusage/memusage.py \\
        examples/memusage/memusage.xtcs examples/ping-yamcs/ping-yamcs.xtcs
    python3 examples/memusage/memusage.py --polls 1   # one round, and stop
    python3 examples/memusage/memusage.py --describe  # what it read

Two configurations are two tcspecials, which must be able to run at once:
``tcs-conflict`` says whether they can. Each must answer to Yamcs
(``gateway: yamcs``), and take its node commands from any port
(``payload_command.source_base`` with port 0), Yamcs sending them from a
port the system chooses.

``--yamcs`` is the directory a Yamcs release unpacks to, holding
``bin/yamcsd``; ``$YAMCS_HOME`` says it when ``--yamcs`` does not, and
where neither does, the Yamcs release the examples are written for is
fetched the first time and kept in ``~/.cache/tcspecial``.
``--no-vehicle`` leaves the tcspecials to somebody else, ``--no-yamcs`` uses
a Yamcs already running on the run directory's configuration, and
``--no-memlock`` runs each tcspecial without locking its memory, for a desk
whose limit on locked memory is too small for the lock.
"""

import argparse
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "python"))

from tcsmoc.processes import Vehicle  # noqa: E402
from tcsmoc.yamcs_ground import (  # noqa: E402
    THREAD_PARAMETERS, UNLIMITED, Yamcs, command_settings, connect,
    query_threads, write_yamcs_instances, yamcs_home)
from tcsprotocol import configuration  # noqa: E402

#: Where Yamcs's web interface and REST API are, unless --http-port says.
HTTP_PORT = 18090

#: How often each tcspecial is asked, in seconds, unless --interval says.
INTERVAL = 5.0

#: The parameter list each instance is given, which Yamcs's web interface
#: shows: the answer's parameters.
PARAMETER_LIST = "memusage"

#: The first sequence number QUERY_THREADS is sent with: past every CONNECT
#: :func:`tcsmoc.yamcs_ground.connect` sends, so that none is answered
#: Stale.
FIRST_SEQUENCE = 1000


def arguments(argv):
    """Reads the command line.

    Args:
        argv: The arguments, without the program's name.

    Returns:
        The options, as :mod:`argparse` gives them.
    """
    parser = argparse.ArgumentParser(
        description="Watch how much memory tcspecial has, and each of its "
                    "threads' stacks, through Yamcs.")
    parser.add_argument(
        "configurations", nargs="*",
        default=[str(HERE / "memusage.xtcs")],
        help="the tcspecial configurations, one for each tcspecial "
             "(default: memusage.xtcs)")
    parser.add_argument("--yamcs", default=os.environ.get("YAMCS_HOME"),
                        help="where Yamcs is unpacked (default: "
                             "$YAMCS_HOME, or else Yamcs fetched the first "
                             "time and kept)")
    parser.add_argument("--run-dir", default="/tmp/memusage",
                        help="where Yamcs's configuration and data are "
                             "written (default: /tmp/memusage)")
    parser.add_argument("--http-port", type=int, default=HTTP_PORT,
                        help=f"Yamcs's web port (default: {HTTP_PORT})")
    parser.add_argument("--interval", type=float, default=INTERVAL,
                        help="seconds between one round of questions and "
                             f"the next (default: {INTERVAL:g})")
    parser.add_argument("--polls", type=int, metavar="N",
                        help="ask N rounds, and stop (default: until "
                             "stopped)")
    parser.add_argument("--describe", action="store_true",
                        help="print what was read and the Yamcs settings, "
                             "and stop")
    parser.add_argument("--no-vehicle", action="store_true",
                        help="do not start tcspecial")
    parser.add_argument("--no-memlock", action="store_true",
                        help="run tcspecial without locking its memory into "
                             "RAM: for a desk whose limit on locked memory "
                             "is too small for it")
    parser.add_argument("--no-yamcs", action="store_true",
                        help="do not start Yamcs; use one already running")
    parser.add_argument("--tcspecial", help="the tcspecial program to run")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="say what it is doing")
    return parser.parse_args(argv)


#: Whether to print status messages: ``-v`` or ``--verbose``.
VERBOSE = False


def status(text):
    """Say ``text`` on stderr, if asked to with ``-v``."""
    if VERBOSE:
        print(text, file=sys.stderr, flush=True)


def instance_name(path, taken):
    """The Yamcs instance a configuration is watched in: its file's name,
    as an instance may be named, made unlike the names already taken.

    Args:
        path:  The configuration's path.
        taken: The names already given.

    Returns:
        The name.
    """
    name = re.sub(r"[^A-Za-z0-9_]", "_", path.stem) or "tcspecial"
    unlike, count = name, 2
    while unlike in taken:
        unlike = f"{name}_{count}"
        count += 1
    return unlike


class Watched:
    """One tcspecial: its configuration, read and checked, and the Yamcs
    instance it is watched in.

    Args:
        path:     The configuration's path.
        instance: The Yamcs instance's name.

    Raises:
        ValueError: The configuration is wrong for this program.
        OSError: The configuration cannot be read.
    """

    def __init__(self, path, instance):
        self.path = Path(path).resolve()
        self.instance = instance
        self.config = configuration.load(self.path)
        gateway = self.config.tcspecial.get("gateway")
        if gateway != "yamcs":
            raise ValueError(f"{self.path}: its gateway is {gateway!r}, and "
                             "this program is Yamcs's: say gateway: yamcs")
        nodes = self.config.node_command_link()
        if nodes is None:
            raise ValueError(f"{self.path}: it has no payload_command, the "
                             "node command link QUERY_THREADS goes on: give "
                             "it payload_command.dest_base and source_base")
        if nodes.send.port != 0:
            raise ValueError(
                f"{self.path}: payload_command.source_base is "
                f"{nodes.send.address}:{nodes.send.port}, and Yamcs sends "
                "QUERY_THREADS from a port the system chooses, which "
                "tcspecial would refuse: make it "
                f"{nodes.send.address}:0, any port of that host")
        self.nodes = nodes.recv
        self.digest, self.why_no_digest = configuration.digest(
            self.path)
        self.next_sequence = FIRST_SEQUENCE

    def sequence(self):
        """The next command's sequence number.

        Returns:
            It, one more than the last.
        """
        sequence = self.next_sequence
        self.next_sequence += 1
        return sequence

    def describe(self):
        """The facts, one per line.

        Returns:
            The instance, the configuration, each Yamcs setting as ``name
            value``, the node command link, and the digest.
        """
        settings = command_settings(self.config)
        lines = [f"instance {self.instance}", f"configuration {self.path}"]
        lines += [f"{name} {value}" for name, value in settings.items()]
        lines += [f"nodes_host {self.nodes.address}",
                  f"nodes_port {self.nodes.port}",
                  f"digest {self.digest}"]
        return "\n".join(lines)


def size(bytes_):
    """A size, as people read one.

    Args:
        bytes_: The size in bytes, or :data:`UNLIMITED`.

    Returns:
        It in KiB, or MiB from ten of those, or "unlimited".
    """
    if bytes_ == UNLIMITED:
        return "unlimited"
    kib = bytes_ / 1024
    if kib >= 10 * 1024:
        return f"{kib / 1024:.1f} MiB"
    return f"{kib:.0f} KiB"


#: What each thread role is called in the report.
ROLES = {"Main": "main", "Signals": "signals", "Commands": "commands",
         "Beacons": "beacons", "Segsend": "segsend", "Node": "node",
         "GroundLink": "ground link"}

#: The node id a thread that belongs to no node is given.
NO_NODE = 2 ** 32 - 1


def report(watched, answer):
    """What a tcspecial said of its memory, as lines to print.

    Args:
        watched: The :class:`Watched` tcspecial.
        answer:  Its answers to QUERY_THREADS, the first's memory and every
                 thread, as :func:`tcsmoc.yamcs_ground.query_threads` gives
                 one, with ``threads`` holding them all.

    Returns:
        The lines: the process's memory, then a line for each thread.
    """
    lines = [f"{watched.instance}: {size(answer['mapped'])} mapped, "
             f"{size(answer['resident'])} resident, "
             f"{size(answer['locked'])} locked, limit "
             f"{size(answer['lock_limit'])}; {answer['total']} threads"]
    nodes = {node.position: node.name
             for node in configuration_nodes(watched.config)}
    for thread in answer["threads"]:
        role = ROLES.get(thread["role"], str(thread["role"]))
        if thread["node"] != NO_NODE:
            role += f" {nodes.get(thread['node'], thread['node'])}"
        share = (100 * thread["deepest"] / thread["stack"]
                 if thread["stack"] else 0)
        lines.append(f"  {role:<24} {size(thread['deepest']):>10} of "
                     f"{size(thread['stack']):>10}  {share:3.0f}%")
    return lines


class _Named:
    """A node's id and name, for the report."""

    def __init__(self, position, name):
        #: Its device id, the position of its name among all of them.
        self.position = position
        #: What the configuration calls it.
        self.name = name


def configuration_nodes(config):
    """Each node's device id and name.

    Args:
        config: The :class:`tcsprotocol.configuration.Configuration`.

    Returns:
        A :class:`_Named` for each node, its id the position of its name
        among every node's, in order, as tcspecial numbers them.
    """
    return [_Named(at, name)
            for at, name in enumerate(sorted(node.name
                                             for node in config.nodes))]


def every_thread(yamcs, watched):
    """Asks one tcspecial QUERY_THREADS until it has told of every thread.

    Args:
        yamcs:   The :class:`Yamcs` instance it is watched in.
        watched: The :class:`Watched` tcspecial.

    Returns:
        The first answer, its ``threads`` holding every thread; or ``None``
        where an answer does not come.
    """
    first = query_threads(yamcs, watched.sequence())
    if first is None:
        return None
    while first["threads"] and len(first["threads"]) < first["total"]:
        more = query_threads(yamcs, watched.sequence(),
                             len(first["threads"]))
        if more is None or not more["threads"]:
            break
        first["threads"] += more["threads"]
    return first


def make_parameter_list(yamcs):
    """Gives an instance the parameter list :data:`PARAMETER_LIST`, of the
    answer's parameters, for Yamcs's web interface to show.

    Args:
        yamcs: The :class:`Yamcs` instance.

    Returns:
        Whether Yamcs made it.
    """
    body = json.dumps({
        "name": PARAMETER_LIST,
        "description": "What tcspecial answered QUERY_THREADS with: the "
                       "memory the whole process has, and each thread's "
                       "stack",
        "patterns": list(THREAD_PARAMETERS)}).encode()
    request = urllib.request.Request(
        f"{yamcs.base}/parameter-lists/{yamcs.instance}/lists", data=body,
        method="POST", headers={"Content-Type": "application/json"})
    try:
        urllib.request.urlopen(request, timeout=5).read()
    except (urllib.error.URLError, OSError) as why:
        status(f"{yamcs.instance}: no parameter list: {why}")
        return False
    return True


def wait_running(yamcs, seconds=60):
    """Waits for an instance to run.

    Args:
        yamcs:   The :class:`Yamcs` instance.
        seconds: How long to wait.

    Returns:
        Whether it runs.
    """
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if yamcs.running():
            return True
        time.sleep(0.5)
    return False


def main(argv):
    """Runs the program, as the module documentation says.

    Args:
        argv: The arguments, without the program's name.

    Returns:
        The exit status: 0, 1 when a tcspecial does not answer, 2 for a
        command line or a configuration this program cannot use.
    """
    global VERBOSE
    options = arguments(argv)
    VERBOSE = options.verbose
    watched = []
    try:
        for path in options.configurations:
            name = instance_name(Path(path),
                                 [one.instance for one in watched])
            watched.append(Watched(path, name))
    except (ValueError, OSError) as why:
        print(f"memusage: {why}", file=sys.stderr)
        return 2
    for one in watched:
        if one.digest is None:
            print(f"memusage: {one.path}: {one.why_no_digest}",
                  file=sys.stderr)
            return 2
    run_dir = Path(options.run_dir)
    if options.describe:
        print("\n\n".join(one.describe() for one in watched))
        return 0

    started = []
    yamcs = None
    try:
        yamcs = Yamcs(None, run_dir, options.http_port, watched[0].instance)
        if not options.no_yamcs:
            try:
                home = yamcs_home(options.yamcs)
            except ValueError as why:
                print(f"memusage: {why}", file=sys.stderr)
                return 2
            write_yamcs_instances([(one.config, one.instance)
                                   for one in watched],
                                  run_dir, options.http_port, home,
                                  "memusage.py")
            yamcs = Yamcs(home, run_dir, options.http_port,
                          watched[0].instance)
            status(f"starting Yamcs on {run_dir}")
            yamcs.start()
        instances = [yamcs] + [yamcs.instance_of(one.instance)
                               for one in watched[1:]]
        for instance in instances:
            if not wait_running(instance):
                print(f"memusage: Yamcs's instance {instance.instance} "
                      "does not run", file=sys.stderr)
                return 1
            make_parameter_list(instance)
        print(f"Yamcs is at http://localhost:{options.http_port}", flush=True)
        if not options.no_vehicle:
            for one in watched:
                vehicle = Vehicle.for_configuration(
                    one.path, options.tcspecial, options.verbose, "all",
                    memlock=not options.no_memlock)
                vehicle.start()
                started.append(vehicle)
        for one, instance in zip(watched, instances):
            if not connect(instance, one.digest, say=status):
                print(f"memusage: {one.path}: the vehicle never answered "
                      "CONNECT with this configuration's checksum",
                      file=sys.stderr)
                return 1
            status(f"{one.instance}: connected")

        polls = 0
        while options.polls is None or polls < options.polls:
            if polls:
                time.sleep(options.interval)
            polls += 1
            for one, instance in zip(watched, instances):
                answer = every_thread(instance, one)
                if answer is None:
                    print(f"{one.instance}: no answer to QUERY_THREADS",
                          flush=True)
                    continue
                print("\n".join(report(one, answer)), flush=True)
        return 0
    except KeyboardInterrupt:
        return 0
    finally:
        for vehicle in started:
            vehicle.stop()
        if yamcs is not None and not options.no_yamcs:
            yamcs.stop()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
