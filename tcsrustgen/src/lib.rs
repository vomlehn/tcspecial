//! A tcspecial configuration, as the Rust that builds it.
//!
//! What tcspecial does today is read a configuration file when it starts. The
//! other way of building it is for the configuration to *become* Rust: a
//! source file, compiled into the executable along with the node types it uses
//! and the infrastructure around them. A vehicle built that way carries no
//! configuration file at all and nothing aboard has to parse one.
//!
//! This is that generator, and it is a program of its own rather than a corner
//! of the editor. It reads a configuration -- YAML or XML, as the extension
//! says -- and writes a `.rs` file. tcsgui runs it from the Edit menu, passing
//! the configuration it is editing and the path from the `rust-code-path`
//! attribute; a Makefile or a build script can run it the same way, which is
//! the point of its being a program: generating the flight software's
//! configuration should not require a window.
//!
//! # What it generates
//!
//! One function, `configuration()`, returning the same
//! [`Graph`](tcslibgs::graph::Graph) the configuration describes -- which is
//! what the flight software already works in. `Graph::check` says whether it
//! can be flown and `runtime::start` opens it, so a configuration compiled in
//! arrives at the same two functions a configuration read from a file does.
//! That is the point of generating this rather than something cleverer: a
//! second representation of a configuration would be a second thing to keep
//! correct, and the one that is checked is this one.
//!
//! What varies between configurations is generated: the nodes, what each says
//! about itself, the links, the payload groups, the command bindings, and what
//! tcspecial itself is configured with. What does not vary -- what an i2c node
//! does, what a mean computes, what the command interpreter answers -- is the
//! code that is already there, and the generated file names those types rather
//! than repeating them.
//!
//! # What it does not do
//!
//! It does not decide whether the configuration is worth generating. A
//! configuration with a node nobody has finished will generate code that
//! builds a `Graph` the flight software refuses, which is the honest answer:
//! the refusal belongs to `Graph::check`, which is one call away in the
//! generated file's own tests. tcsgui asks that question before it runs this,
//! because an editor has somebody to tell; a Makefile has `tcsverify`.

use std::path::Path;

use tcslibgs::graph::{parameters, section_of, Graph, Section};

/// Read the configuration at `configuration` and write its Rust to `output`.
///
/// The whole of what the program does, so that a caller with two paths needs
/// nothing else. The directory of `output` is made if it is not there:
/// somebody who asked for `generated/vehicle.rs` meant the directory as much
/// as the file.
///
/// `Err` carries a sentence to print. Every failure here is a path or a file:
/// a configuration that cannot be read, a directory that cannot be made, a
/// file that cannot be written.
pub fn generate(configuration: &Path, output: &Path) -> Result<(), String> {
    let graph = Graph::load(configuration)
        .map_err(|e| format!("{}: {e}", configuration.display()))?;

    if let Some(parent) = output.parent() {
        if !parent.as_os_str().is_empty() {
            std::fs::create_dir_all(parent)
                .map_err(|e| format!("{} cannot be made: {e}", parent.display()))?;
        }
    }
    std::fs::write(output, rust_of(&graph, configuration))
        .map_err(|e| format!("{} cannot be written: {e}", output.display()))
}

/// The configuration as Rust.
///
/// `from` is the configuration this was generated from, which the file names
/// at the top: a reader who finds it in a tree has to be able to get back to
/// the thing it was made of.
pub fn rust_of(graph: &Graph, from: &Path) -> String {
    let mut out = String::new();
    let named = from
        .file_name()
        .map(|name| name.to_string_lossy().to_string())
        .unwrap_or_else(|| from.display().to_string());

    out.push_str(&format!(
        "//! What this vehicle carries, as Rust.\n\
         //!\n\
         //! Generated by tcsrustgen from `{named}`. Every generation \
         overwrites this\n\
         //! file whole, so nothing written here by hand survives: the \
         configuration is\n\
         //! the thing to edit, and this is what comes of it.\n\
         //!\n\
         //! It builds the same `Graph` the configuration describes, which is \
         what the\n\
         //! flight software already works in: `Graph::check` says whether it \
         can be\n\
         //! flown and `runtime::start` opens it, so a configuration compiled \
         in arrives\n\
         //! at the same two functions a configuration read from a file does.\n\
         \n"
    ));

    out.push_str(
        "use std::collections::{BTreeMap, BTreeSet};\n\
         \n\
         use tcslibgs::graph::parameters::nest;\n\
         use tcslibgs::graph::{\n    \
             CommandBinding, Destinations, Graph, Group, Link, Node,\n\
         };\n\
         use tcslibgs::Scalar;\n\
         \n",
    );

    out.push_str(
        "/// The configuration this file was generated from.\n\
         pub fn configuration() -> Graph {\n    \
             Graph {\n",
    );

    out.push_str(&format!(
        "        description: {},\n",
        option_of(graph.description.as_deref())
    ));

    // What tcspecial itself is configured with, flat and dotted as the rules
    // name it: `nest` is what puts the file's subsections back, and calling it
    // here keeps this file from spelling out a tree of `Parameter`s.
    //
    // `rust-code-path` is left out. It says where this file goes, which is not
    // something the vehicle is told -- and a field carried into the flight
    // software and never acted on is a field somebody will one day believe in.
    out.push_str("        tcspecial: Some(nest(&[\n");
    if let Some(said) = &graph.tcspecial {
        for (attribute, value) in parameters::flatten(said) {
            if value.as_str().trim().is_empty() || attribute == parameters::RUST_CODE {
                continue;
            }
            out.push_str(&format!(
                "            ({}.to_string(), Scalar::of({})),\n",
                quoted(&attribute),
                quoted(value.as_str())
            ));
        }
    }
    out.push_str("        ]\n        .into_iter()\n        .collect())),\n");

    out.push_str("        groups: vec![\n");
    for group in &graph.groups {
        out.push_str(&format!(
            "            Group {{ name: {}.to_string(), interval: {}.to_string() }},\n",
            quoted(&group.name),
            quoted(&group.interval)
        ));
    }
    out.push_str("        ],\n");

    // The nodes, in the order the sections are read: the ground link, the
    // vehicle's own graph, then what it carries. A reader of this file and a
    // reader of the configuration meet them in the same order.
    out.push_str("        nodes: vec![\n");
    for section in [Section::Moc, Section::Vehicle, Section::Payloads] {
        for node in graph
            .nodes
            .iter()
            .filter(|node| section_of(&node.node_type) == section)
        {
            out.push_str("            Node {\n");
            out.push_str(&format!(
                "                name: {}.to_string(),\n",
                quoted(&node.name)
            ));
            out.push_str(&format!(
                "                node_type: {}.to_string(),\n",
                quoted(&node.node_type)
            ));
            out.push_str(&format!(
                "                group: {},\n",
                option_of(node.group.as_deref())
            ));
            if node.attributes.is_empty() {
                out.push_str("                attributes: BTreeMap::new(),\n");
            } else {
                out.push_str("                attributes: [\n");
                for (attribute, value) in &node.attributes {
                    out.push_str(&format!(
                        "                    ({}.to_string(), Scalar::of({})),\n",
                        quoted(attribute),
                        quoted(value.as_str())
                    ));
                }
                out.push_str(
                    "                ]\n                .into_iter()\n                \
                     .collect(),\n",
                );
            }
            out.push_str("            },\n");
        }
    }
    out.push_str("        ],\n");

    // The links, each naming the data source it leaves by and every sink it
    // reaches: the shape the file reader builds, so a rule about a link reads
    // the same whether the configuration was compiled in or read.
    out.push_str("        links: vec![\n");
    for link in &graph.links {
        let destinations: Vec<String> = link
            .to
            .each()
            .iter()
            .map(|to| format!("{}.to_string()", quoted(to)))
            .collect();
        out.push_str(&format!(
            "            Link {{\n                \
                 from: {}.to_string(),\n                \
                 to: Destinations::of(vec![{}]),\n                \
                 comment: None,\n            \
             }},\n",
            quoted(&link.from),
            destinations.join(", ")
        ));
    }
    out.push_str("        ],\n");

    out.push_str("        commands: vec![\n");
    for command in &graph.commands {
        out.push_str(&format!(
            "            CommandBinding {{ from: {}.to_string(), sets: {}.to_string() }},\n",
            quoted(&command.from),
            quoted(&command.sets)
        ));
    }
    out.push_str("        ],\n");

    // Which files it was read from, which file each node came from, where each
    // was drawn, and what the editor was told not to raise. All empty, and
    // that is the honest answer: a configuration compiled in was read from no
    // file at all, and nothing aboard draws it. The first two exist so that a
    // complaint about a node can name the page it is on.
    out.push_str(
        "        files: Vec::new(),\n        \
         homes: BTreeMap::new(),\n        \
         placed: BTreeMap::new(),\n        \
         set_aside: BTreeSet::new(),\n    }\n}\n",
    );

    out
}

/// A string as Rust spells it.
fn quoted(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// An `Option<String>` as Rust spells it.
fn option_of(value: Option<&str>) -> String {
    match value.map(str::trim).filter(|value| !value.is_empty()) {
        Some(value) => format!("Some({}.to_string())", quoted(value)),
        None => "None".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The repository's root, for the shipped configurations.
    fn root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
    }

    /// The generated file says what it is and where it came from.
    ///
    /// A derived file that does not say so is a file somebody edits.
    #[test]
    fn the_generated_file_says_it_is_generated() {
        let from = root().join("tests/manual/thermostat.yaml");
        let graph = Graph::load(&from).expect("the worked example");
        let rust = rust_of(&graph, &from);

        assert!(rust.starts_with("//!"), "{}", &rust[..40]);
        assert!(
            rust.contains("Generated by tcsrustgen from `thermostat.yaml`"),
            "{rust}"
        );
        assert!(
            rust.contains("nothing written here by hand survives"),
            "a generated file says not to edit it"
        );
    }

    /// Where the code goes is where the caller said, and the directory is made.
    #[test]
    fn it_writes_where_it_was_told_and_makes_the_directory() {
        let where_ = tempfile::tempdir().expect("a directory");
        let output = where_.path().join("generated/vehicle.rs");

        generate(&root().join("tests/manual/thermostat.yaml"), &output)
            .expect("the worked example generates");
        let rust = std::fs::read_to_string(&output).expect("the generated code");
        assert!(rust.contains("pub fn configuration() -> Graph"), "{rust}");
        assert!(rust.contains("\"temp_fore\""), "{rust}");
        // Where it went is not in it: that is where the code goes, not
        // something the vehicle is told.
        assert!(!rust.contains("rust-code-path"), "{rust}");
    }

    /// A configuration that cannot be read is said so, and nothing is written.
    #[test]
    fn a_configuration_that_cannot_be_read_is_reported() {
        let where_ = tempfile::tempdir().expect("a directory");
        let output = where_.path().join("vehicle.rs");
        let said = generate(&where_.path().join("nothing-here.yaml"), &output)
            .expect_err("a file that is not there");

        assert!(said.contains("nothing-here.yaml"), "{said}");
        assert!(!output.exists(), "something was written anyway");
    }

    /// The committed example is what this generator writes.
    ///
    /// A generated file that nothing compiles is a generator that can emit
    /// something which does not build, and nobody would find out until a build
    /// of the flight software failed. So the generated form of the shipped
    /// thermostat is committed and compiled by `tests/generated.rs`, which
    /// then hands what it builds to `Graph::check`.
    ///
    /// Set TCSGUI_WRITE_EXAMPLE to write it out after a deliberate change to
    /// the generator, as the shipped examples are written.
    #[test]
    fn the_committed_example_is_what_the_generator_writes() {
        let from = root().join("tests/manual/thermostat.yaml");
        let graph = Graph::load(&from).expect("the worked example");
        let written = rust_of(&graph, &from);
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/generated/thermostat.rs");

        if std::env::var("TCSGUI_WRITE_EXAMPLE").is_ok() {
            std::fs::create_dir_all(path.parent().expect("a directory"))
                .expect("the directory is writable");
            std::fs::write(&path, &written).expect("the example is writable");
            return;
        }

        let committed = std::fs::read_to_string(&path).unwrap_or_else(|e| {
            panic!(
                "{}: {e}. Run the tests with TCSGUI_WRITE_EXAMPLE=1 to write it out",
                path.display()
            )
        });
        assert_eq!(
            committed,
            written,
            "{} is not what the generator writes any more",
            path.display()
        );
    }
}
