#!/usr/bin/env python3
"""The thermostat example with Yamcs as the ground station.

The vehicle is the thermostat example's: three sensors of one zone, each
converted to kelvin, a vote between them, and a thermostat that switches two
heaters as the zone's temperature leaves a band about its setpoint, with
tcssim simulating the sensors and the heaters on a physics model of the
zone. What differs is the ground end of the link: Yamcs
(https://yamcs.org), which speaks CCSDS packets, so the configuration's
gateway is ``yamcs``, and every packet to and from the ground carries a
CCSDS primary header.

This program puts the pieces together:

* it writes a Yamcs configuration from the tcspecial one, with
  ``tcslib/yamcs_ground.py``: the ports, the APIDs, and a mission database
  generated by ``tcslibgs/yamcs.py`` in which every node drawn into the
  gateway node has a parameter of the type the configuration says its data
  are -- the readings and the vote as temperatures in kelvin, the
  thermostat's decision as on or off -- as tcsmoc's plot window and the F´
  bridge know them;
* it starts Yamcs on it, tcssim on the simulator file beside the
  configuration, and tcspecial on the configuration once tcssim says it is
  ready, each killed when this program exits, however it exits;
* it has Yamcs send a CONNECT carrying the configuration's checksum until
  the vehicle answers with it -- the vehicle sends nothing down until it
  has -- and then reads what arrives back from Yamcs, over its REST API:
  the zone's temperature, the three readings, the thermostat's decision and
  the heaters it drives, and the beacon; and the simulated world's ambient
  temperature, which the vehicle does not send: it is read from the
  simulator file by ``tcsverify --ambient`` and set in Yamcs as a local
  parameter, ``world_ambient_temp``;
* it shows them in a window, the beacon panel above the thermostat's, or
  with ``--seconds`` prints them for that long with no window, a line each
  ``--every`` seconds and a line whenever the heaters are switched.

Yamcs's web interface, at http://localhost:17090 by default, shows every
packet and parameter meanwhile, each temperature with its unit.

Usage, from the repository's root, with Yamcs unpacked somewhere::

    python3 examples/thermostat-yamcs/thermostat_yamcs.py --yamcs ~/yamcs
    python3 examples/thermostat-yamcs/thermostat_yamcs.py --seconds 120
    python3 examples/thermostat-yamcs/thermostat_yamcs.py --describe

``--yamcs`` is the directory a Yamcs release unpacks to, holding
``bin/yamcsd``; ``$YAMCS_HOME`` says it when ``--yamcs`` does not.
``--no-vehicle``, ``--no-simulator`` and ``--no-yamcs`` leave tcspecial,
tcssim and Yamcs to somebody else. tcssim draws a window of its own, so it
wants a display; every payload of it sends from the start, as though its
panel's button had been pressed.
"""

import argparse
import os
import queue
import subprocess
import sys
import threading
import time
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "python"))

from tcslib.beacon import Schedule  # noqa: E402
from tcslib.processes import Child, Vehicle, built  # noqa: E402
from tcslib.yamcs_ground import (  # noqa: E402
    Yamcs, YamcsBeacons, command_settings, connect, print_beacon_pass,
    write_yamcs, yamcs_home)
from tcslibgs import configuration  # noqa: E402
from tcslibgs import yamcs as generated  # noqa: E402
from tcslibgs.form import DECISION, UNITS, Form  # noqa: E402

#: Where Yamcs's web interface and REST API are, unless --http-port says.
HTTP_PORT = 17090

#: The Yamcs instance this example runs.
INSTANCE = "thermostat"

#: The run's simulation mode, given to tcssim and tcspecial: every payload
#: simulated, as the examples' run targets have it.
SIMULATE = "all"

#: How long tcssim is given to say it is ready, in seconds.
SIMULATOR_PATIENCE = 60

#: What the simulated world's ambient temperature is shown as: a source of
#: its own, though nothing on the vehicle sends it.
WORLD = "world ambient"

#: What a value is shown as before one has arrived.
NOTHING_YET = "--"

#: How often the window takes in what the reading loop has reported, in
#: milliseconds.
REFRESH_MS = 100


def arguments(argv):
    """Reads the command line.

    Args:
        argv: The arguments, without the program's name.

    Returns:
        The options, as :mod:`argparse` gives them.
    """
    parser = argparse.ArgumentParser(description="Watch a tcspecial "
                                                 "thermostat through Yamcs.")
    parser.add_argument(
        "configuration", nargs="?",
        default=str(HERE / "thermostat-yamcs.xtcs"),
        help="the tcspecial configuration (default: thermostat-yamcs.xtcs)")
    parser.add_argument("--yamcs", default=os.environ.get("YAMCS_HOME"),
                        help="where Yamcs is unpacked (default: $YAMCS_HOME)")
    parser.add_argument("--run-dir", default="/tmp/thermostat-yamcs",
                        help="where Yamcs's configuration and data are "
                             "written (default: /tmp/thermostat-yamcs)")
    parser.add_argument("--http-port", type=int, default=HTTP_PORT,
                        help=f"Yamcs's web port (default: {HTTP_PORT})")
    parser.add_argument("--seconds", type=float, metavar="N",
                        help="print what arrives for N seconds, and stop, "
                             "with no window")
    parser.add_argument("--every", type=float, default=2.0, metavar="S",
                        help="with --seconds, print a line each S seconds "
                             "(default: 2)")
    parser.add_argument("--describe", action="store_true",
                        help="print what was read and the Yamcs settings, "
                             "and stop")
    parser.add_argument("--no-vehicle", action="store_true",
                        help="do not start tcspecial")
    parser.add_argument("--no-simulator", action="store_true",
                        help="do not start tcssim")
    parser.add_argument("--no-yamcs", action="store_true",
                        help="do not start Yamcs; use one already running")
    parser.add_argument("--tcspecial", help="the tcspecial program to run")
    parser.add_argument("--tcssim", help="the tcssim program to run")
    parser.add_argument("--tcsverify",
                        help="the tcsverify program that gives the "
                             "configuration's checksum")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="say what it is doing")
    options = parser.parse_args(argv)
    if options.every <= 0:
        parser.error("--every is a number of seconds above nought")
    return options


#: Whether to print status messages: ``-v`` or ``--verbose``.
VERBOSE = False


def status(text):
    """Say ``text`` on stderr, if asked to with ``-v``.

    Args:
        text: What to say.
    """
    if VERBOSE:
        print(text, file=sys.stderr, flush=True)


@dataclass(frozen=True)
class Source:
    """A node drawn into the gateway node, as Yamcs has its data."""

    #: The node's name.
    node: str
    #: Its parameter's qualified name.
    parameter: str
    #: What the configuration says its data are: a
    #: :class:`tcslibgs.form.Form`.
    form: object
    #: The nodes a decision of its drives, by its ``moc-out`` links:
    #: the heaters, for the thermostat.
    drives: tuple = ()


class Setup:
    """What the program read out of the configuration, and the Yamcs
    settings that follow from it.

    Args:
        options: The command line's options, from :func:`arguments`.

    Raises:
        ValueError: The configuration is wrong for this program.
        OSError: The configuration cannot be read.
    """

    def __init__(self, options):
        self.path = Path(options.configuration).resolve()
        self.config = configuration.load(self.path)
        said = self.config.tcspecial
        if said.get("gateway") != "yamcs":
            raise ValueError(f"{self.path}: its gateway is "
                             f"{said.get('gateway')!r}, and this program is "
                             "Yamcs's: say gateway: yamcs")
        gateways = [node.name for node in self.config.nodes
                    if node.node_type == "gateway_yamcs"]
        if len(gateways) != 1:
            raise ValueError(f"{self.path}: {len(gateways)} gateway_yamcs "
                             "nodes, and this program reads the data of one")
        self.gateway = gateways[0]
        self.beacon = self.config.beacon_link()
        self.beacon_interval = self.config.beacon_interval()
        self.links = [link for link in generated.telemetry(self.config)
                      if link.gateway == self.gateway]
        self.sources = []
        for link in self.links:
            if link.form.kind == "Lines":
                # Each line is a source of its own, on or off as it is high
                # or low: a line sensing a heater is the heater's state.
                self.sources += [
                    Source(f"{link.source} line {offset}",
                           generated.qualified(f"{link.name}_line{offset}"),
                           DECISION)
                    for offset in link.form.lines]
                continue
            self.sources.append(Source(link.source,
                                       generated.qualified(link.name),
                                       link.form, self._drives(link)))
        if not any(source.form.kind == "Value" for source in self.sources):
            raise ValueError(f'{self.path}: nothing drawn into '
                             f'"{self.gateway}" sends values, and this '
                             "program shows a thermostat's temperatures")
        self.digest, self.why_no_digest = configuration.digest(
            self.path, options.tcsverify)
        # The simulated world's ambient temperature, which the vehicle does
        # not send, read from the simulator file and set in Yamcs as a local
        # parameter, so that Yamcs shows the surroundings beside the zone.
        self.ambient, self.why_no_ambient = configuration.ambient(
            self.path, options.tcsverify)
        self.world = None
        if self.ambient is not None:
            kelvin = next(unit for unit in UNITS if unit.symbol == "K")
            self.world = Source(WORLD, generated.qualified(
                generated.WORLD_AMBIENT), Form("Value", kelvin))

    def _drives(self, link):
        """The nodes a source's decisions drive.

        Args:
            link: The source's :class:`tcslibgs.yamcs.Telemetry`.

        Returns:
            The names its ``moc-out`` links reach, in order, for a
            source of decisions; none for any other.
        """
        if link.form.kind != "Decision":
            return ()
        targets = self.config.node(link.source).links.get("moc-out", [])
        return tuple(target.split(".", 1)[0] for target in targets)

    def describe(self, run_dir, http_port):
        """The facts, one per line, as the agreement test reads them.

        Args:
            run_dir:   Where Yamcs's configuration and data go.
            http_port: Yamcs's web port.

        Returns:
            Each setting as ``name value``; then each source as ``source``,
            its name, its APID, the port it arrives at and its form, as
            the Rust's ``Debug`` writes a ``Form``; then the digest.
        """
        lines = [f"http_port {http_port}", f"run_dir {run_dir}"]
        lines += [f"{name} {value}" for name, value in
                  command_settings(self.config).items()]
        lines.append(f"uplink_apid {self.config.uplink_apid(self.gateway)}")
        for link in self.links:
            lines.append(f"source {link.source} {link.apid} "
                         f"{link.ground.port} {link.form}")
        lines.append(f"digest {self.digest}")
        return "\n".join(lines)


def shown(source, value, units):
    """A value as the program shows it.

    Args:
        source: The :class:`Source` it is from.
        value:  Its engineering value as Yamcs gave it, or ``None`` before
                one has arrived.
        units:  Its units, as Yamcs's mission database states them.

    Returns:
        A temperature to three places with its unit, a decision as ``on``
        or ``off``, bytes as hex, or :data:`NOTHING_YET`.
    """
    if value is None:
        return NOTHING_YET
    if source.form.kind == "Value":
        return " ".join([f"{value:.3f}"] + list(units))
    if source.form.kind == "Decision":
        return "on" if value else "off"
    return value.hex() if isinstance(value, bytes) else str(value)


class Readings:
    """What the vehicle's sources last said, read from Yamcs.

    Args:
        yamcs:   The Yamcs they arrive at.
        sources: The :class:`Source` of each.
        feeding: Each source's name, by those of the others whose data
                 arrive at it: :func:`feeding_of`.
    """

    def __init__(self, yamcs, sources, feeding):
        self._yamcs = yamcs
        self.sources = sources
        self._feeding = feeding
        self.units = {source.parameter: yamcs.units(source.parameter)
                      for source in sources}
        self.values = {}

    def read(self):
        """Read each source's latest value from Yamcs.

        Returns:
            Each decision that changed, as ``(source, was, now)``, ``was``
            ``None`` for the first that arrived.
        """
        latest = self._yamcs.latest([source.parameter
                                     for source in self.sources])
        changed = []
        for source in self.sources:
            if source.parameter not in latest:
                continue
            value = latest[source.parameter][0]
            was = self.values.get(source.parameter)
            if source.form.kind == "Decision" and value != was:
                changed.append((source, was, value))
            self.values[source.parameter] = value
        return changed

    def text(self, source):
        """A source's latest value, as the program shows it.

        Args:
            source: The :class:`Source`.

        Returns:
            See :func:`shown`.
        """
        return shown(source, self.values.get(source.parameter),
                     self.units[source.parameter])

    def arrived(self):
        """Whether every source has said something.

        Returns:
            True once each has a value.
        """
        return all(source.parameter in self.values
                   for source in self.sources)

    def line(self):
        """Every source's latest value, on one line.

        Returns:
            Each value as ``name value``, the vote's first, then each
            reading, then each decision and what it drives.
        """
        parts = []
        for source in self.ordered():
            parts.append(f"{source.node} {self.text(source)}")
            for driven in source.drives:
                parts.append(f"{driven} {self.text(source)}")
        return ", ".join(parts)

    def ordered(self):
        """The sources in the order they are shown.

        Returns:
            Values first -- one fed by others before what feeds it, so the
            zone's temperature comes before the readings voted on -- then
            decisions, then anything else, each by name within.
        """
        rank = {"Value": 0, "Decision": 1}

        def key(source):
            """Where a source is shown.

            Args:
                source: The :class:`Source`.

            Returns:
                Its rank, then whether it is fed by none, then its name.
            """
            return (rank.get(source.form.kind, 2),
                    not self._is_fed(source), source.node)

        return sorted(self.sources, key=key)

    def _is_fed(self, source):
        """Whether another source's links arrive at this one.

        Args:
            source: The :class:`Source`.

        Returns:
            True for a vote between readings.
        """
        return bool(self._feeding.get(source.node))


def feeding_of(config, sources):
    """Which sources' data arrive at each source.

    Args:
        config:  The configuration.
        sources: The :class:`Source` of each.

    Returns:
        Each source's name, by the names of those that feed it.
    """
    names = {source.node for source in sources}
    feeding = {name: [] for name in names}
    for node in config.nodes:
        if node.name not in names:
            continue
        for targets in node.links.values():
            for target in targets:
                name = target.split(".", 1)[0]
                if name in names:
                    feeding[name].append(node.name)
    return feeding


def say_changes(changed, readings):
    """Print each decision that changed, with the temperatures it was made
    on.

    Args:
        changed:  What :meth:`Readings.read` gave.
        readings: The :class:`Readings`.
    """
    for source, was, now in changed:
        if was is None:
            continue
        # What a decision drives, where it drives anything: a line sensing a
        # heater drives nothing, being the heater's state.
        driving = (f", driving {', '.join(source.drives)}" if source.drives
                   else "")
        print(f"switched: {source.node} {shown(source, was, [])} -> "
              f"{shown(source, now, [])}{driving}; "
              f"{readings.line()}", flush=True)


def watch_and_print(readings, beacons, seconds, every):
    """Print what arrives for a while, with no window.

    Args:
        readings: The :class:`Readings`.
        beacons:  The beacon link.
        seconds:  How long.
        every:    How often to print every value, in seconds.

    Returns:
        The exit status: nought where every source said something, one where
        one never did.
    """
    deadline = time.monotonic() + seconds
    next_line = time.monotonic()
    while time.monotonic() < deadline:
        # A pass of the beacon loop is a quarter of a second long, which
        # paces this loop.
        print_beacon_pass(beacons.next_pass())
        say_changes(readings.read(), readings)
        if time.monotonic() >= next_line:
            print(f"read: {readings.line()}", flush=True)
            next_line += every
    if readings.arrived():
        return 0
    missing = [source.node for source in readings.sources
               if source.parameter not in readings.values]
    print(f"thermostat_yamcs: nothing arrived from {', '.join(missing)}",
          file=sys.stderr)
    return 1


def run_the_window(readings, beacons):
    """The window -- the beacon panel above the thermostat's -- and the loop
    that reads Yamcs for it.

    Args:
        readings: The :class:`Readings`.
        beacons:  The beacon link.

    Returns:
        The exit status, nought, once the window is closed.
    """
    import tkinter as tk
    from tkinter import ttk

    from tcsui import fonts, theme
    from tcsui.beacon_panel import BeaconPanel, Shown

    reports = queue.Queue()

    def reading_loop():
        """Report each beacon pass, and the readings after it, for ever."""
        while True:
            beacon_pass = beacons.next_pass()
            for remark in beacon_pass.remarks:
                status(remark)
            for warning in beacon_pass.warnings:
                print(warning, file=sys.stderr, flush=True)
            say_changes(readings.read(), readings)
            reports.put(Shown.of(beacon_pass))

    window = tk.Tk()
    fonts.use_in(window)
    theme.use_in(window)
    window.title("tcspecial thermostat through Yamcs")
    window.resizable(False, False)
    between = theme.BETWEEN
    beacon = BeaconPanel(window)
    beacon.pack(fill="x", padx=between, pady=(between, between // 2))
    panel = ttk.LabelFrame(window, text="Thermostat, through Yamcs",
                           padding=theme.INSIDE)
    panel.pack(fill="x", padx=between, pady=(between // 2, between))

    rows = []
    for source in readings.ordered():
        names = [(source.node, source)]
        names += [(driven, source) for driven in source.drives]
        for name, shown_from in names:
            number = len(rows)
            ttk.Label(panel, text=f"{name}:").grid(row=number, column=0,
                                                   sticky="w", pady=2)
            value = ttk.Label(panel, style="Value.TLabel", width=14)
            value.grid(row=number, column=1, sticky="w",
                       padx=(between, 0), pady=2)
            rows.append((value, shown_from))
    labels = [label for label in beacon.grid_slaves(column=0)
              + panel.grid_slaves(column=0)
              if int(label.grid_info()["columnspan"]) == 1]
    label_width = max(label.winfo_reqwidth() for label in labels)
    for box in (beacon, panel):
        box.columnconfigure(0, minsize=label_width)

    def take_in():
        """Show what the loop has reported, and come back in
        :data:`REFRESH_MS`."""
        while True:
            try:
                beacon.show(reports.get_nowait())
            except queue.Empty:
                break
        for value, source in rows:
            value.configure(text=readings.text(source))
        window.after(REFRESH_MS, take_in)

    threading.Thread(target=reading_loop, daemon=True).start()
    window.after(REFRESH_MS, take_in)
    window.mainloop()
    return 0


def simulator_ready(config_path, program, patience):
    """Wait for tcssim to say it is ready for this run, as ``tcssim --wait``
    asks it: set up for this configuration, its simulator file and
    :data:`SIMULATE`.

    Args:
        config_path: The configuration.
        program:     The tcssim program.
        patience:    How long to wait, in seconds.

    Raises:
        RuntimeError: It is not ready in time, or is set up for another run.
    """
    asked = subprocess.run(
        [str(program), f"--simulate={SIMULATE}", f"--wait={patience}",
         str(config_path)], capture_output=True, text=True)
    if asked.returncode != 0:
        raise RuntimeError("tcssim is not ready for this run: "
                           f"{asked.stderr.strip() or asked.stdout.strip()}")


def main(argv):
    """Runs the example.

    Args:
        argv: The command line, without the program's name.

    Returns:
        The exit status.
    """
    global VERBOSE
    options = arguments(argv)
    VERBOSE = options.verbose
    run_dir = Path(options.run_dir).resolve()
    try:
        setup = Setup(options)
    except (ValueError, OSError) as why:
        print(f"thermostat_yamcs: {why}", file=sys.stderr)
        return 2
    if options.describe:
        print(setup.describe(run_dir, options.http_port))
        return 0
    if setup.digest is None:
        print("thermostat_yamcs: no checksum for CONNECT: "
              f"{setup.why_no_digest}", file=sys.stderr)
        return 2
    yamcs = Yamcs(options.yamcs, run_dir, options.http_port, INSTANCE)
    started = []
    try:
        if not options.no_yamcs:
            home = yamcs_home(options.yamcs)
            write_yamcs(setup.config, run_dir, options.http_port, home,
                        INSTANCE, "thermostat_yamcs.py",
                        world=setup.world is not None)
            status(f"starting Yamcs on {run_dir}")
            yamcs.start()
            status(f"Yamcs is at http://localhost:{options.http_port}")
        if not options.no_simulator:
            tcssim = options.tcssim or built("tcssim", "say --no-simulator")
            # Every payload sending from the start, as though each of its
            # panel's buttons had been pressed: the sensors report the zone
            # and the heaters take what they are driven to without anybody
            # at tcssim's window. Each can still be stopped there.
            simulator = Child(tcssim, [f"--simulate={SIMULATE}", "--sending",
                                       str(setup.path)], "tcssim",
                              options.verbose)
            simulator.start()
            started.append(simulator)
            status("waiting for tcssim to make its simulated devices")
            simulator_ready(setup.path, tcssim, SIMULATOR_PATIENCE)
        if not options.no_vehicle:
            vehicle = Vehicle.for_configuration(setup.path, options.tcspecial,
                                                options.verbose, SIMULATE)
            vehicle.start()
            started.append(vehicle)
        if not connect(yamcs, setup.digest, say=status):
            print("thermostat_yamcs: the vehicle never answered CONNECT with "
                  "this configuration's checksum", file=sys.stderr)
            return 1
        print("connected: the vehicle is running this configuration",
              flush=True)
        beacons = YamcsBeacons(yamcs, setup.beacon,
                               Schedule.for_interval(setup.beacon_interval),
                               setup.digest, setup.beacon_interval)
        sources = setup.sources + [setup.world] * (setup.world is not None)
        if setup.world is None:
            status("no simulated world's temperature: "
                   f"{setup.why_no_ambient}")
        else:
            yamcs.set_value(setup.world.parameter, setup.ambient)
        readings = Readings(yamcs, sources,
                            feeding_of(setup.config, sources))
        for source in readings.ordered():
            units = " ".join(readings.units[source.parameter]) or "none"
            print(f"parameter: {source.parameter}, {source.form}, units "
                  f"{units}", flush=True)
        if options.seconds is None:
            return run_the_window(readings, beacons)
        return watch_and_print(readings, beacons, options.seconds,
                               options.every)
    except (RuntimeError, ValueError, OSError) as why:
        print(f"thermostat_yamcs: {why}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 0
    finally:
        for child in reversed(started):
            child.stop()
        if not options.no_yamcs:
            yamcs.stop()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
