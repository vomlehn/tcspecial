#!/usr/bin/env python3
"""Writes tcslibgs/src/unit_table.rs from the value types of
tcslibgs/xtce/types.xtce, which are the one statement of the units: see
`make unit-table` in tcslibgs/.

Each value type gives one unit: its name the enum variant, its short
description the variant's comment, its unit set the symbol a file writes,
its calibrator's coefficient the size of a step, and its tcspecial.name and
tcspecial.step ancillary data what the unit and its step are called in a
sentence. A value type is a FloatParameterType; nothing else in the
document is a unit.

Arguments: the document, and the Rust file to write.
"""
import sys
import xml.etree.ElementTree as ET

X = {"x": "http://www.omg.org/spec/XTCE/20250214"}


def variant(name):
    """Makes a Rust enum variant of a type's name.

    Arguments:
        name    The type's name, in words joined by underscores.

    Returns:
        The words capitalised and run together: metre_per_second is
        MetrePerSecond.
    """
    return "".join(word.capitalize() for word in name.split("_"))


def steps(coefficient, name):
    """Says how many of a unit's steps make one of it.

    Arguments:
        coefficient The calibrator's coefficient, as the document writes
                    it: what one step is, in the unit.
        name        The type's name, for a complaint.

    Returns:
        The number of steps, as Rust writes a power of ten: 1e6.
    """
    count = round(1 / float(coefficient))
    exponent = len(str(count)) - 1
    if count != 10 ** exponent:
        sys.exit(f"unit-table: {name}: a step of {coefficient} is not a "
                 f"power of ten")
    return f"1e{exponent}"


def units(document):
    """Reads the units out of the document.

    Arguments:
        document    The path of types.xtce.

    Returns:
        A list of (variant, description, symbol, name, steps, step), one per
        value type, in the order the document states them.
    """
    found = []
    for kind in ET.parse(document).getroot().iterfind(
            ".//x:ParameterTypeSet/x:FloatParameterType", X):
        name = kind.get("name")
        said = {datum.get("name"): datum.text
                for datum in kind.iterfind(".//x:AncillaryData", X)}
        term = kind.find(".//x:PolynomialCalibrator/x:Term", X)
        symbol = kind.find("x:UnitSet/x:Unit", X)
        if (term is None or symbol is None
                or "tcspecial.name" not in said
                or "tcspecial.step" not in said):
            sys.exit(f"unit-table: {name}: a value type needs a unit, a "
                     f"calibrator, tcspecial.name and tcspecial.step")
        found.append((variant(name), kind.get("shortDescription", ""),
                      symbol.text, said["tcspecial.name"],
                      steps(term.get("coefficient"), name),
                      said["tcspecial.step"]))
    return found


def rust(found):
    """Writes the table as Rust.

    Arguments:
        found   The units, as units() reads them.

    Returns:
        The text of unit_table.rs.
    """
    lines = ["// @generated by `make unit-table` in tcslibgs/ from",
             "// xtce/types.xtce: change that and rerun it.",
             "",
             "/// A unit a value may be in.",
             "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, "
             "Ord)]",
             "pub enum Unit {"]
    for name, description, _, _, _, _ in found:
        lines += [f"    /// {description}", f"    {name},"]
    lines += ["}", "",
              "impl Unit {",
              "    /// Every unit, in the order of the table.",
              f"    pub const ALL: [Unit; {len(found)}] = ["]
    lines += [f"        Unit::{name}," for name, *_ in found]
    lines += ["    ];", "}", "",
              "/// The table, one row per value type.",
              f"const TABLE: [Row; {len(found)}] = ["]
    for name, _, symbol, said, count, step in found:
        lines += ["    Row {",
                  f"        unit: Unit::{name},",
                  f"        symbol: \"{symbol}\",",
                  f"        name: \"{said}\",",
                  f"        per_unit: {count},",
                  f"        step: \"{step}\",",
                  "    },"]
    lines += ["];", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    document, out = sys.argv[1], sys.argv[2]
    with open(out, "w", encoding="utf-8") as written:
        written.write(rust(units(document)))
