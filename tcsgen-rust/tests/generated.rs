//! The generated Rust compiles, and says what the configuration said.
//!
//! `tcsgen-rust` writes a configuration out as Rust, to be compiled into
//! tcspecial along with the node types the configuration uses. A generator
//! whose output is only compared against expected text is a generator that can
//! emit something that does not compile, and nobody would find out until a
//! build of the flight software failed -- so the output is committed here, as
//! `generated/thermostat.rs`, and this test file compiles it.
//!
//! Which makes the compiler the test: the generated code names `HostPort` from
//! `tcslibgs`, so a change to it that the generator has not kept up with is a
//! build failure here rather than a surprise in somebody's vehicle build. And
//! what it holds is then compared against the same configuration read from its
//! file and put through the same two calls the flight software reads the
//! section with: a configuration compiled in says what a configuration read
//! from a file says.
//!
//! The committed file is regenerated by
//! `TCSGUI_WRITE_EXAMPLE=1 cargo test -p tcsgen-rust`, as the shipped examples
//! are. `tcsgen-rust/src/lib.rs` is where the test that regenerates it lives,
//! next to the generator; this file is only the compiling and the comparing.

use std::path::PathBuf;
use std::time::Duration;

use tcslibgs::graph::{parameters, Graph};
use tcslibgs::CIConfig;

#[path = "generated/thermostat.rs"]
mod thermostat;

/// The shipped configuration, as the flight software reads its section.
fn said() -> CIConfig {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let graph =
        Graph::load(root.join("tests/manual/thermostat.yaml")).expect("the shipped example reads");
    let section = graph.tcspecial.expect("the shipped example has a section");

    parameters::ci_config_of(&parameters::flatten(&section))
        .expect("the section holds together")
        .to_ci_config()
        .expect("every socket in it is one socket")
}

/// What the generator wrote is what the configuration says.
///
/// Read the file, build the struct from the generated code, and compare every
/// attribute: a generator that silently dropped the beacon's address would
/// otherwise emit code that compiles and flies beacons nowhere.
#[test]
fn the_generated_settings_are_the_ones_the_file_describes() {
    let said = said();
    let built = thermostat::tcspecial();

    // tcs_cmd.recv is the one the command interpreter holds apart, as the
    // address it answers on and the port that goes with it.
    assert_eq!(built.tcs_cmd.recv.address, said.address);
    assert_eq!(built.tcs_cmd.recv.port, said.port);
    assert_eq!(built.tcs_cmd.send, said.moc_cmd_send);

    assert_eq!(
        built.payload_command.source_base,
        said.payload_command_source_base
    );
    assert_eq!(
        built.payload_command.dest_base,
        said.payload_command_dest_base
    );
    assert_eq!(built.payload_telemetry.source_base, said.payload_source_base);
    assert_eq!(built.payload_telemetry.dest_base, said.payload_dest_base);

    assert_eq!(
        built.beacon.interval,
        Duration::from_millis(said.beacon_interval.0 as u64)
    );
    assert_eq!(built.beacon.send, said.beacon_send);
    assert_eq!(built.beacon.recv, said.beacon_recv);

    assert_eq!(
        built.log.directory,
        said.log_dir.as_deref().map(PathBuf::from)
    );
    assert_eq!(built.log.segment_size, said.log_segment_bytes);
}

/// And it is held as what it means, not as the text the file spelled it in.
///
/// The worked example's own values, written here as a reader of the
/// configuration would say them: a socket split into an address and a port,
/// five seconds as a duration, a directory as a path. Nothing compiled in has
/// to be made sense of at startup.
#[test]
fn the_generated_settings_are_typed() {
    let built = thermostat::tcspecial();

    assert_eq!(built.tcs_cmd.recv.address, "0.0.0.0");
    assert_eq!(built.tcs_cmd.recv.port, 4000);
    assert_eq!(built.beacon.interval, Duration::from_secs(5));
    assert_eq!(
        built.log.directory,
        Some(PathBuf::from("/var/log/tcspecial"))
    );
    assert_eq!(built.log.segment_size, 65_536);

    // And a payload's own socket is the base counted on by its id, which is
    // the arithmetic `HostPort::at` is the one place for.
    let third = built
        .payload_telemetry
        .source_base
        .at(2)
        .expect("a payload three ports above the base");
    assert_eq!(third.port, built.payload_telemetry.source_base.port + 2);
}
