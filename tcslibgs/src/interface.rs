//! The interface: the XTCE documents every packet on the link is stated in.
//!
//! Two programs speak the same interface when the tcs-xtce digests of their
//! documents are the same. That digest is of what the documents mean -- it
//! leaves out comments, whitespace and the order of the members of a set --
//! and tcs-xtce computes it alike in Rust, C/C++ and Python, so a ground
//! station in any of them can compare its copy with what the vehicle speaks.
//!
//! The vehicle says which interface it speaks in every beacon, from
//! [`InterfaceDigest::of_this_build`]: the digest of the documents in
//! `tcslibgs/xtce/` this build was generated from. A ground station reads its
//! own copy with [`InterfaceDigest::of_files`] and compares the two. See "The
//! Interface, the Fallback and Switching Over" in `docs/design.rst`.

use std::fmt;
use std::path::Path;

use crate::error::{TcsError, TcsResult};
use crate::interface_digest::INTERFACE_DIGEST;

/// The tcs-xtce digest of a set of XTCE documents.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct InterfaceDigest(pub [u8; 16]);

impl InterfaceDigest {
    /// The interface this build was generated from, and so the one it speaks.
    ///
    /// A constant, generated by `make interface-digest` in `tcslibgs/` when
    /// the documents change, rather than computed as the program starts: a
    /// vehicle need not carry the documents to say which ones it speaks, and
    /// what it says cannot then depend on files that may have changed since
    /// it was built. A test here computes it again from the documents, so a
    /// constant that was not regenerated is a test that fails.
    pub fn of_this_build() -> InterfaceDigest {
        InterfaceDigest(INTERFACE_DIGEST)
    }

    /// Digests the interface a set of XTCE documents state.
    ///
    /// The order they are given in does not matter. Reading and digesting
    /// them allocates, so a program does this as it starts and not in its
    /// main loop.
    ///
    /// # Arguments
    ///
    /// * `paths` - The XTCE documents, taken as one set.
    ///
    /// # Returns
    ///
    /// The interface they state.
    ///
    /// # Errors
    ///
    /// [`TcsError::Config`], naming the documents, if they cannot be read or
    /// digested.
    pub fn of_files<P: AsRef<Path>>(paths: &[P]) -> TcsResult<InterfaceDigest> {
        tcs_xtce::digest::digest_files_bytes(paths)
            .map(InterfaceDigest)
            .map_err(|why| {
                let named: Vec<String> = paths
                    .iter()
                    .map(|path| path.as_ref().display().to_string())
                    .collect();
                TcsError::Config(format!(
                    "the interface cannot be read from {}: {why}; give the \
                     XTCE documents the vehicle was built from",
                    named.join(", ")
                ))
            })
    }

    /// Says why the interface the vehicle speaks is not this station's.
    ///
    /// # Arguments
    ///
    /// * `theirs` - The interface the vehicle speaks.
    /// * `ours`   - The interface this station read.
    ///
    /// # Returns
    ///
    /// A message saying what to do, or `None` when the two are the same.
    pub fn differs(
        theirs: InterfaceDigest,
        ours: InterfaceDigest,
    ) -> Option<String> {
        (theirs != ours).then(|| {
            format!(
                "the vehicle speaks interface {theirs} and this station read \
                 {ours}: give this station the XTCE documents the vehicle was \
                 built from, or upload the station's to the vehicle"
            )
        })
    }
}

impl fmt::Display for InterfaceDigest {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        for byte in self.0 {
            write!(f, "{byte:02x}")?;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Lists the documents this build's interface is stated in: every XTCE
    /// document in `tcslibgs/xtce/`, as `make interface-digest` takes them.
    ///
    /// # Returns
    ///
    /// Their paths, sorted.
    ///
    /// # Panics
    ///
    /// If the directory cannot be read.
    fn documents() -> Vec<std::path::PathBuf> {
        let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("xtce");
        let mut found: Vec<_> = std::fs::read_dir(&dir)
            .expect("tcslibgs/xtce")
            .map(|entry| entry.expect("an entry").path())
            .filter(|path| path.extension().is_some_and(|ext| ext == "xml"))
            .collect();
        found.sort();
        found
    }

    /// The constant is the digest of the documents as they are now, so a
    /// document changed without `make interface-digest` is caught here and
    /// not by a ground station that cannot read the vehicle.
    #[test]
    fn this_builds_interface_is_the_digest_of_its_documents() {
        assert_eq!(
            InterfaceDigest::of_files(&documents()).expect("they read"),
            InterfaceDigest::of_this_build(),
            "an XTCE document in tcslibgs/xtce/ has changed: run `make \
             interface-digest` in tcslibgs/ and commit what it writes"
        );
    }

    #[test]
    fn documents_that_cannot_be_read_say_which() {
        let why = InterfaceDigest::of_files(&["/nonexistent/fallback.xml"])
            .expect_err("there is no such file");
        assert!(
            why.to_string().contains("/nonexistent/fallback.xml"),
            "{why}"
        );
    }

    #[test]
    fn two_interfaces_differ_only_when_their_digests_do() {
        let one = InterfaceDigest([1; 16]);
        let two = InterfaceDigest([2; 16]);
        assert_eq!(InterfaceDigest::differs(one, one), None);
        let why = InterfaceDigest::differs(one, two).expect("they differ");
        assert!(why.contains(&one.to_string()), "{why}");
        assert!(why.contains(&two.to_string()), "{why}");
    }
}
